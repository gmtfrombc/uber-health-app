// Global error handlers
void _handlePlatformError(Object error, StackTrace stack) {
  _logError('Platform error', error, stack);
}

void _handleFlutterError(FlutterErrorDetails details) {
  _logError(
    'Flutter error',
    details.exception,
    details.stack ?? StackTrace.empty,
  );
}

Future<void> _handleZoneError(Object error, StackTrace stack) async {
  _logError('Zone error', error, stack);
}

void _logError(String type, Object error, StackTrace stack) {
  // Check for specific error types to provide better guidance
  bool isInheritedWidgetError =
      error.toString().contains('deactivated widget') ||
      error.toString().contains('Looking up a deactivated widget');

  // Log errors in debug mode
  if (kDebugMode) {
    debugPrint('$type: $error');
    if (isInheritedWidgetError) {
      debugPrint(
        'INHERITED WIDGET ERROR DETECTED: This is likely a Provider access after widget disposal',
      );
      debugPrint(
        'RECOMMENDATION: Store Provider references in variables during initState()',
      );
    }
    debugPrint('Stack trace: $stack');
  }

  // In production, you would send this to a remote logging service
  // like Firebase Crashlytics, Sentry, etc.

  // For deactivated widget errors, we should not show the UI error since it's a development issue
  if (!isInheritedWidgetError) {
    // Optionally show an error UI if the app is already running
    _showErrorUI(error.toString(), stack);
  }
}

void _showErrorUI(String errorMessage, [StackTrace? stack]) {
  // Only show UI if the app is running and we have access to the navigator
  if (navigatorKey.currentContext != null) {
    // Show a snackbar or dialog with the error
    final context = navigatorKey.currentContext!;

    // Only proceed if we can safely use this context
    if (!context.mounted) {
      debugPrint('Cannot show error UI: context is not mounted');
      return;
    }

    // Determine if this is a serious error that needs detailed reporting
    bool isSeriousError =
        errorMessage.contains("Firebase") ||
        errorMessage.contains("Exception") ||
        errorMessage.contains("Error") ||
        stack != null;

    // Use a future delayed to ensure this runs after the current build cycle
    Future.microtask(() {
      try {
        if (isSeriousError && context.mounted) {
          // For serious errors, show the detailed error screen
          Navigator.of(context).push(
            MaterialPageRoute(
              builder:
                  (context) => ErrorDetailsScreen(
                    errorMessage: errorMessage,
                    stackTrace: stack?.toString(),
                    timestamp: DateTime.now(),
                    onRetry: () {
                      Navigator.of(context).pop();
                      // Here you could add logic to retry the last operation if applicable
                    },
                  ),
            ),
          );
        } else if (context.mounted) {
          // For minor errors, just show a snackbar
          ScaffoldMessenger.of(context).showSnackBar(
            SnackBar(
              content: Text(
                'An unexpected error occurred. Please try again later.',
              ),
              backgroundColor: Colors.red,
              duration: Duration(seconds: 5),
              action: SnackBarAction(
                label: 'Details',
                textColor: Colors.white,
                onPressed: () {
                  // Show error details screen when user requests more information
                  if (context.mounted) {
                    Navigator.of(context).push(
                      MaterialPageRoute(
                        builder:
                            (context) => ErrorDetailsScreen(
                              errorMessage: errorMessage,
                              stackTrace: stack?.toString(),
                              timestamp: DateTime.now(),
                            ),
                      ),
                    );
                  }
                },
              ),
            ),
          );
        }
      } catch (e) {
        // Last resort - if we can't show the error UI, just log it
        debugPrint('Failed to show error UI: $e');
      }
    });
  } else {
    debugPrint('Cannot show error UI: no valid context available');
  }
}

