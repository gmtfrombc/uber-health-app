// Add a provider initializer widget to initialize providers when the app starts
class ProviderInitializer extends StatefulWidget {
  final Widget child;

  const ProviderInitializer({super.key, required this.child});

  @override
  ProviderInitializerState createState() => ProviderInitializerState();
}

class ProviderInitializerState extends State<ProviderInitializer> {
  StreamSubscription<User?>? _authSubscription;

  @override
  void initState() {
    super.initState();
    _initializeProviders();
  }

  Future<void> _initializeProviders() async {
    // Initialize providers after user authentication
    _authSubscription = FirebaseAuth.instance.authStateChanges().listen((
      User? user,
    ) {
      if (!mounted) return; // Ensure widget is still mounted
      if (user != null) {
        // User is logged in, initialize providers
        final userProvider = Provider.of<UserProvider>(context, listen: false);
        final appointmentProvider = Provider.of<AppointmentProvider>(
          context,
          listen: false,
        );
        // Get medical questions provider reference
        final medicalQuestionsProvider = Provider.of<MedicalQuestionsProvider>(
          context,
          listen: false,
        );

        // Initialize user profile and appointments
        userProvider.initialize();
        appointmentProvider.initialize();

        // Don't navigate here - let the AuthWrapper handle navigation based on user role
        // This prevents overriding the provider dashboard navigation

        // Initialize medical questions provider
        Future.delayed(const Duration(milliseconds: 500), () {
          if (mounted) {
            // Initialize medical questions provider
            medicalQuestionsProvider.initialize();
          }
        });
      } else {
        // User signed out, clear data if needed (optional)
        Provider.of<UserProvider>(context, listen: false).clearUserData();
        // AuthWrapper will handle navigation back to sign-in
      }
    });
  }

  @override
  void dispose() {
    _authSubscription?.cancel(); // Cancel the listener
    super.dispose();
  }

  @override
  Widget build(BuildContext context) {
    return widget.child;
  }
}
