Future<void> main() async {
  WidgetsFlutterBinding.ensureInitialized();

  // Check for network connectivity to Firebase servers
  if (kDebugMode) {
    await checkFirebaseAvailability();
  }

  await initializeFirebaseWithRetry();

  // Sign out any existing user at app launch to prevent session conflicts
  await FirebaseAuth.instance.signOut();
  if (kDebugMode) {
    debugPrint('User signed out at app launch');
  }

  runApp(const MyApp());
}

// Check if Firebase services are reachable
Future<void> checkFirebaseAvailability() async {
  try {
    debugPrint('Checking Firebase availability...');

    // Try to connect to common Firebase endpoints
    var firebaseHosts = [
      'firestore.googleapis.com',
      'firebase.googleapis.com',
      'firebaseio.com',
    ];

    for (var host in firebaseHosts) {
      try {
        final result = await InternetAddress.lookup(host);
        if (result.isNotEmpty && result[0].rawAddress.isNotEmpty) {
          debugPrint('$host is reachable');
        }
      } on SocketException {
        debugPrint('Cannot reach $host');
      }
    }
  } catch (e) {
    debugPrint('Error checking Firebase availability: $e');
  }
}

Future<void> initializeFirebaseWithRetry() async {
  int maxRetries = 3;
  int retryCount = 0;
  bool initialized = false;

  while (!initialized && retryCount < maxRetries) {
    try {
      // Try to initialize Firebase with a timeout
      await Firebase.initializeApp(
        options: DefaultFirebaseOptions.currentPlatform,
      ).timeout(
        const Duration(seconds: 10),
        onTimeout: () {
          throw TimeoutException(
            'Firebase initialization timed out after 10 seconds',
          );
        },
      );

      initialized = true;

      if (kDebugMode) {
        debugPrint('Firebase initialized with production configuration');
      }
    } catch (e) {
      retryCount++;
      if (kDebugMode) {
        debugPrint('Failed to initialize Firebase: $e');

        // More detailed error information
        if (e is FirebaseException) {
          debugPrint('FirebaseException: ${e.code} - ${e.message}');
          debugPrint('Plugin: ${e.plugin}');
        } else if (e is SocketException) {
          debugPrint('SocketException: ${e.message}');
          debugPrint('Address: ${e.address?.address}, Port: ${e.port}');
        } else if (e is TimeoutException) {
          debugPrint('TimeoutException: Connection timed out');
        }

        debugPrint('Retry attempt $retryCount of $maxRetries');
      }

      if (retryCount < maxRetries) {
        await Future.delayed(Duration(seconds: 2 * retryCount));
      }
    }
  }

  if (!initialized) {
    if (kDebugMode) {
      debugPrint('Failed to initialize Firebase after $maxRetries attempts');
    }
    // You might want to show an error dialog or handle this case
  }
}

